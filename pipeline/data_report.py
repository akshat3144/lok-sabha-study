"""Data-quality report for the final analysis table.

    python -I -X utf8 pipeline/data_report.py   -> data/final/DATA_REPORT.md (+ data_report.json)
"""
import glob
import gzip
import json
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "data")


def pct(x):
    return f"{100 * x:.1f}%"


def main():
    plan = json.load(open(os.path.join(D, "raw", "api", "plan.json")))
    planned = sum(p["records"] for p in plan)
    saved = unrec = 0
    for f in glob.glob(os.path.join(D, "raw", "api", "ls*", "*.json.gz")):
        o = json.loads(gzip.decompress(open(f, "rb").read()))[0]
        saved += len(o["listOfQuestions"])
        unrec += len(o.get("_unrecoverable_record_index") or [])
    cr = json.load(open(os.path.join(D, "clean", "clean_report.json")))
    q = pd.read_parquet(os.path.join(D, "final", "questions_analysis.parquet"),
                        columns=["qid", "ls", "session", "date", "qtype", "answer_text", "answer_missing",
                                 "statement_empty", "n_question_parts", "all_parts_covered", "minister_name",
                                 "needs_ocr", "answer_garbled", "qa_mismatch", "boilerplate", "source_a",
                                 "ministry_group", "asker_bloc", "govt_period", "majority_type", "n_askers"])
    p = pd.read_parquet(os.path.join(D, "measures", "parts.parquet"), columns=["qid", "answer_missing_for_part"])
    p["ls"] = p["qid"].str.extract(r"^ls(\d+)")[0].astype(int)
    mp = pd.read_csv(os.path.join(D, "ref", "mp_party.csv"), low_memory=False)
    man = pd.read_csv(os.path.join(D, "ref", "mp_party_manual.csv"), low_memory=False)
    val = open(os.path.join(D, "ref", "mp_party_validation.txt"), encoding="utf-8").read()
    sw = [l.strip() for l in val.splitlines() if "switcher failures" in l]

    L = ["# Data-quality report: Lok Sabha Question Hour corpus, 1999–2026", "",
         f"*Generated by `pipeline/data_report.py` from the final tables. Clean build {cr['generated']}.*", "",
         "## 1. Collection funnel",
         "| Step | Records |", "|---|---|",
         f"| Listed by the official sansad.in API (sum of per-session totals) | {planned:,} |",
         f"| Saved | {saved:,} ({pct(saved / planned)}) |",
         f"| Unrecoverable on the server (HTTP 500 even one record at a time, network OK) | {unrec:,} |",
         f"| Unique questions after removing exact duplicates | {cr['rows']:,} ({cr['duplicates_dropped']} duplicates) |",
         f"| Replacement answer files (docx/pdf/htm) indexed | {cr.get('fallback_files_indexed', 'n/a'):,} |", "",
         "## 2. Coverage by Lok Sabha",
         "| LS | Questions | Sessions | Dates | Starred | Answer text | Parts | Parts with answer | All parts covered | Minister parsed |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for ls, d in q.groupby("ls"):
        pp = p[p.ls == ls]
        has_ans = d["answer_text"].fillna("").str.strip().str.len() > 0
        L.append(f"| {ls} | {len(d):,} | {d['session'].nunique()} | {d['date'].dropna().min()} – {d['date'].dropna().max()} | "
                 f"{pct((d['qtype'] == 'starred').mean())} | {pct(has_ans.mean())} | {len(pp):,} | "
                 f"{pct(1 - pp['answer_missing_for_part'].mean())} | {pct(d['all_parts_covered'].fillna(False).mean())} | "
                 f"{pct(d['minister_name'].notna().mean())} |")
    tot_ans = (q["answer_text"].fillna("").str.strip().str.len() > 0).mean()
    L += [f"| **All** | **{len(q):,}** | | | {pct((q['qtype'] == 'starred').mean())} | **{pct(tot_ans)}** | "
          f"**{len(p):,}** | **{pct(1 - p['answer_missing_for_part'].mean())}** | | |", ""]

    src = q["source_a"].fillna("none").value_counts()
    L += ["## 3. Answer-text sources", "| Source | Questions |", "|---|---|"] + \
         [f"| {k} | {v:,} |" for k, v in src.items()] + [""]

    L += ["## 4. Flags (counts)", "| Flag | Questions |", "|---|---|",
          f"| Answer still missing | {int(q['answer_missing'].fillna(False).sum()):,} |",
          f"| Statement laid but body missing | {int(q['statement_empty'].fillna(False).sum()):,} |",
          f"| Image-only answer (needs OCR) | {int(q['needs_ocr'].fillna(False).sum()):,} |",
          f"| Garbled answer text | {int(q['answer_garbled'].fillna(False).sum()):,} |",
          f"| Question/answer mismatch | {int(q['qa_mismatch'].fillna(False).sum()):,} |",
          f"| ≥1 boilerplate non-answer phrase detected | {int(q['boilerplate'].apply(lambda b: b is not None and len(b) > 0).sum()):,} |",
          ""]

    L += ["## 5. Askers: party at election and role on the question date",
          f"- **Asker names matched to a party at election: {mp['party_at_election'].notna().mean():.1%}** of "
          f"{len(mp):,} distinct (Lok Sabha, asker) names. None are flagged for review; "
          f"{len(man):,} were resolved or confirmed by hand with a source each.",
          f"- Known party-switcher checks: {sw[0] if sw else 'n/a'}.",
          f"- Questions with no date (so no role): {int(q['govt_period'].isna().sum())}.", "",
          "| LS | Government | Opposition | Outside support | Mixed | Unresolved |", "|---|---|---|---|---|---|"]
    for ls, d in q.groupby("ls"):
        c = d["asker_bloc"].value_counts()
        L.append(f"| {ls} | {c.get('government', 0):,} | {c.get('opposition', 0):,} | "
                 f"{c.get('outside_support', 0):,} | {c.get('mixed', 0):,} | {c.get('unresolved', 0):,} |")
    L += ["", "| Government period | Majority type | Questions |", "|---|---|---|"]
    for (gpid, mt), n in q.groupby(["govt_period", "majority_type"]).size().items():
        L.append(f"| {gpid} | {mt} | {n:,} |")
    L += ["", "## 6. Ministry groups", "| Group | Questions |", "|---|---|"] + \
         [f"| {k} | {v:,} |" for k, v in q["ministry_group"].fillna("UNMAPPED").value_counts().items()]
    L += ["", "## 7. Known limitations (to report in the paper)",
          f"- {unrec:,} questions are listed by sansad.in but broken on the server, and {int(q['answer_missing'].fillna(False).sum()):,} "
          "questions still have no answer text: mainly 1999–2009 \"statement laid\" answers with no file link, plus image-only "
          "scans that await OCR.",
          "- Party = party ticket at the MP's election or by-election. Mid-term defections are handled only for documented "
          "party splits (Shiv Sena 2022, NCP 2023, LJP 2021, TMC 2026), using faction lists. Other individual defections are not modelled.",
          "- Three LS16 names (Bhola Singh, Dr. Bhola Singh, Satya Pal Singh) belong to two same-party MPs each; the party is "
          "certain but the constituency is ambiguous.",
          "- 2024–26 answers come from official Word/PDF files, while earlier ones come from API text. A pre-registered parity check covers this.",
          "- 26 of the 90 coalition-spell rows are low-confidence (mostly small parties or month-level dates). "
          "`asker_bloc_strict` drops them for robustness.",
          "- The raw text is copyright of the Lok Sabha Secretariat: it must not be redistributed. Publish only derived measures and code."]
    out = os.path.join(D, "final", "DATA_REPORT.md")
    open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    json.dump({"planned": planned, "saved": saved, "unrecoverable": unrec, "rows": len(q), "parts": len(p),
               "answer_text_pct": round(100 * tot_ans, 2)}, open(os.path.join(D, "final", "data_report.json"), "w"), indent=2)
    print("\n".join(L))


if __name__ == "__main__":
    main()
